type AppContext = Context<AppEnv>;

// Grant IDs are generated by the library (16 characters); this only keeps garbage out of the lookups.
const GRANT_ID_PATTERN = /^[A-Za-z0-9_-]{1,128}$/;

const connectionNotFound = "MCP 接続が見つかりません";
const botNotFound = "Bot が見つかりません";
const oauthUnavailableMessage = "この接続先では MCP 接続を確認できません";
const targetMessage = "connection_id か grant_id のどちらか一方を指定してください";

// The connection or the grant that an operation is about: exactly one of the two.
type Target = { connectionId: string } | { grantId: string };

function parseTarget(body: Record<string, unknown>): Target | "invalid" | "not_found" {
  const hasConnection = "connection_id" in body;
  const hasGrant = "grant_id" in body;
  if (hasConnection === hasGrant) return "invalid";
  const value = hasConnection ? body.connection_id : body.grant_id;
  if (typeof value !== "string") return "invalid";
  if (hasConnection) return MCP_CONNECTION_ID_PATTERN.test(value) ? { connectionId: value } : "not_found";
  return GRANT_ID_PATTERN.test(value) ? { grantId: value } : "not_found";
}

type AssignInput = { target: Target | null; botId: string | null };

const assignBody = jsonBody<AssignMcpConnectionRequest, AssignInput, AppEnv>((body, c) => {
  const unknown = unknownField(body, ["connection_id", "grant_id", "bot_id"]);
  if (unknown !== null) return apiError(c, 400, "invalid_request", `未知の項目があります: ${unknown}`);
  const target = parseTarget(body);
  if (target === "invalid") return apiError(c, 400, "invalid_request", targetMessage);
  const botId = body.bot_id;
  if (botId !== null && typeof botId !== "string") {
    return apiError(c, 400, "invalid_request", "bot_id は Bot の ID か null にしてください");
  }
  // A malformed ID is answered as missing, after the form is checked.
  if (target === "not_found" || (botId !== null && !BOT_ID_PATTERN.test(botId))) {
    return { ok: true, value: { target: null, botId: null } };
  }
  return { ok: true, value: { target, botId } };
});

const revokeBody = jsonBody<RevokeMcpConnectionRequest, { target: Target | null }, AppEnv>((body, c) => {
  const unknown = unknownField(body, ["connection_id", "grant_id"]);
  if (unknown !== null) return apiError(c, 400, "invalid_request", `未知の項目があります: ${unknown}`);
  const target = parseTarget(body);
  if (target === "invalid") return apiError(c, 400, "invalid_request", targetMessage);
  return { ok: true, value: { target: target === "not_found" ? null : target } };
});

// The client names of legacy grants, looked up once per client.
function clientNames(oauth: OAuthHelpers) {
  const cache = new Map<string, Promise<string>>();
  return (clientId: string) => {
    let name = cache.get(clientId);
    if (name === undefined) {
      name = clientName(oauth, clientId);
      cache.set(clientId, name);
    }
    return name;
  };
}

function botOf(row: McpConnectionRow, bots: Map<string, BotRow>): McpConnection["bot"] {
  const bot = row.botId === null ? undefined : bots.get(row.botId);
  return bot === undefined || bot.deletedAt !== null ? null : { id: bot.id, name: bot.name };
}

async function toApiConnection(
  entry: ClassifiedConnection,
  bots: Map<string, BotRow>,
  nameOf: (clientId: string) => Promise<string>,
): Promise<McpConnection> {
  switch (entry.kind) {
    case "active":
    case "expired":
      return {
        kind: entry.kind,
        id: entry.row.id,
        grant_id: null,
        client_name: entry.row.clientName,
        redirect_host: redirectHost(entry.row.redirectUri),
        bot: botOf(entry.row, bots),
        created_at: entry.row.createdAt,
      };
    case "legacy":
    case "stale": {
      const row = entry.kind === "stale" ? entry.row : null;
      return {
        kind: entry.kind,
        id: null,
        grant_id: entry.grant.id,
        client_name: row?.clientName ?? (await nameOf(entry.grant.clientId)),
        redirect_host: redirectHost(entry.grant.redirectUri ?? row?.redirectUri ?? ""),
        bot: null,
        // Grants have seconds.
        created_at: entry.grant.createdAt * 1000,
      };
    }
  }
}

type Snapshot = { grants: GrantSummary[]; rows: McpConnectionRow[]; entries: ClassifiedConnection[] };

// The grants in KV (every page) and the rows of the user, matched.
async function snapshot(db: Db, oauth: OAuthHelpers, userId: string, now: number): Promise<Snapshot> {
  const [grants, rows] = await Promise.all([listAllUserGrants(oauth, userId), listUserConnections(db, userId)]);
  return { grants, rows, entries: classifyConnections(grants, rows, now) };
}

function findEntry(entries: ClassifiedConnection[], target: Target): ClassifiedConnection | undefined {
  if ("connectionId" in target) {
    return entries.find((e) => (e.kind === "active" || e.kind === "expired") && e.row.id === target.connectionId);
  }
  return entries.find((e) => (e.kind === "legacy" || e.kind === "stale" || e.kind === "active") && e.grant?.id === target.grantId);
}

// The connection after a change, as the list shows it.
async function connectionResponse(c: AppContext, oauth: OAuthHelpers, id: string): Promise<McpConnection | null> {
  const db = c.get("db");
  const row = await findUserConnection(db, c.get("user").id, id);
  if (!row || row.revokedAt !== null) return null;
  const bots = await workspaceBotsByIds(db, c.get("workspace").id, row.botId === null ? [] : [row.botId]);
  return toApiConnection({ kind: "active", row, grant: null }, bots, clientNames(oauth));
}

// The only active MCP Events subscription of the user without a connection, when a legacy grant taken in now can
// claim it: the bot is mcp, the grant is the only legacy grant, there is exactly one such subscription, and it was
// refreshed after the grant was made. Otherwise the AI's next subscribe records its connection.
async function claimableSubscription(
  c: AppContext,
  snap: Snapshot,
  grant: GrantSummary,
  bot: BotRow | null,
  now: number,
): Promise<string | null> {
  if (bot === null || bot.deliveryKind !== "mcp") return null;
  if (snap.entries.filter((e) => e.kind === "legacy").length !== 1) return null;
  const { results } = await c.env.DB.prepare(
    `SELECT id, updated_at FROM subscriptions
    WHERE user_id = ? AND kind = 'mcp' AND connection_id IS NULL AND unsubscribed_at IS NULL AND expires_at > ?
    LIMIT 2`,
  )
    .bind(c.get("user").id, now)
    .all<{ id: string; updated_at: number }>();
  const only = results.length === 1 ? results[0] : undefined;
  return only !== undefined && only.updated_at >= grant.createdAt * 1000 ? only.id : null;
}

export const mcpConnectionsApi = new Hono<AppEnv>()
  .use("*", requireUser, requirePersonalWorkspace)
  .get("/", async (c) => {
    const oauth = c.env.OAUTH_PROVIDER;
    if (!oauth) return apiError(c, 503, "temporarily_unavailable", oauthUnavailableMessage);
    const db = c.get("db");
    const snap = await snapshot(db, oauth, c.get("user").id, clock.now());
    const botIds = snap.entries.flatMap((e) =>
      (e.kind === "active" || e.kind === "expired") && e.row.botId !== null ? [e.row.botId] : [],
    );
    const bots = await workspaceBotsByIds(db, c.get("workspace").id, botIds);
    const nameOf = clientNames(oauth);
    const connections = await Promise.all(snap.entries.map((entry) => toApiConnection(entry, bots, nameOf)));
    connections.sort((a, b) => b.created_at - a.created_at);
    const body: McpConnectionList = { connections };
    return c.json(body, 200);
  })
  .post("/assign", assignBody, async (c) => {
    const oauth = c.env.OAUTH_PROVIDER;
    if (!oauth) return apiError(c, 503, "temporarily_unavailable", oauthUnavailableMessage);
    const { target, botId } = c.req.valid("json");
    if (target === null) return apiError(c, 404, "not_found", connectionNotFound);
    const db = c.get("db");
    const userId = c.get("user").id;
    const workspaceId = c.get("workspace").id;
    const bot = botId === null ? null : await findActiveWorkspaceBot(db, workspaceId, botId);
    if (bot === undefined) return apiError(c, 404, "not_found", botNotFound);

    const now = clock.now();
    const snap = await snapshot(db, oauth, userId, now);
    const entry = findEntry(snap.entries, target);
    if (entry === undefined) return apiError(c, 404, "not_found", connectionNotFound);
    if (entry.kind === "expired") {
      return apiError(c, 400, "connection_expired", "期限切れの接続は Bot に割り当てられません。AI から接続し直してください");
    }
    if (entry.kind === "stale") {
      return apiError(c, 400, "connection_stale", "切断済みの接続は Bot に割り当てられません。AI から接続し直してください");
    }
    if (entry.kind === "active" && "grantId" in target) {
      return apiError(c, 400, "invalid_request", "この接続は connection_id で指定してください");
    }

    const d1 = c.env.DB;
    let connectionId: string;
    let statements: D1PreparedStatement[];
    let replacement: Replacement;
    if (entry.kind === "active") {
      connectionId = entry.row.id;
      replacement = {
        userId,
        workspaceId,
        connectionId,
        oauthClientId: entry.row.oauthClientId,
        botId: bot?.id ?? null,
        sameApp: null,
        now,
      };
      statements = [
        ...(bot === null ? [] : replacementStatements(d1, replacement)),
        d1
          .prepare(
            `UPDATE mcp_connections SET bot_id = ?3, updated_at = ?8
            WHERE id = ?2 AND user_id = ?1 AND revoked_at IS NULL AND ${BOT_ALIVE}`,
          )
          .bind(...replacementValues(replacement, 8)),
      ];
    } else {
      // A legacy grant is taken in: it gets a row.
      const grant = entry.grant;
      connectionId = newMcpConnectionId(now);
      replacement = {
        userId,
        workspaceId,
        connectionId,
        oauthClientId: grant.clientId,
        botId: bot?.id ?? null,
        sameApp: null,
        now,
      };
      const name = await clientName(oauth, grant.clientId);
      const claimed = await claimableSubscription(c, snap, grant, bot, now);
      statements = [
        ...(bot === null ? [] : replacementStatements(d1, replacement)),
        d1
          .prepare(
            `INSERT INTO mcp_connections (id, user_id, workspace_id, bot_id, grant_id, oauth_client_id, client_name,
              redirect_uri, created_at, updated_at, revoked_at, revoke_reason)
            SELECT ?2, ?1, ?7, ?3, ?10, ?9, ?11, ?12, ?8, ?8, NULL, NULL WHERE ${BOT_ALIVE}`,
          )
          .bind(...replacementValues(replacement), grant.id, name, grant.redirectUri ?? ""),
        ...(claimed === null
          ? []
          : [
              d1
                .prepare(
                  `UPDATE subscriptions SET connection_id = ?1
                  WHERE id = ?2 AND user_id = ?3 AND connection_id IS NULL AND unsubscribed_at IS NULL
                    AND EXISTS (SELECT 1 FROM mcp_connections WHERE id = ?1)`,
                )
                .bind(connectionId, claimed, userId),
            ]),
      ];
    }

    let results: D1Result<RevokedRow>[];
    try {
      results = await d1.batch<RevokedRow>(statements);
    } catch (error) {
      // Two requests taking in the same grant.
      if (isUniqueViolation(error)) return apiError(c, 409, "conflict", "この接続は別の操作で更新されました。画面を読み込み直してください");
      throw error;
    }
    const changedIndex = bot === null ? 0 : 2;
    if ((results[changedIndex]?.meta.changes ?? 0) === 0) {
      // The bot or the connection went away meanwhile; nothing was replaced.
      return apiError(c, 404, "not_found", connectionNotFound);
    }
    const revoked = bot === null ? [] : (results[1]?.results ?? []);
    await revokeConnectionGrants(oauth, userId, revoked, null);

    const body = await connectionResponse(c, oauth, connectionId);
    if (!body) return apiError(c, 404, "not_found", connectionNotFound);
    return c.json(body, 200);
  })
  .post("/revoke", revokeBody, async (c) => {
    const oauth = c.env.OAUTH_PROVIDER;
    if (!oauth) return apiError(c, 503, "temporarily_unavailable", oauthUnavailableMessage);
    const { target } = c.req.valid("json");
    if (target === null) return apiError(c, 404, "not_found", connectionNotFound);
    const db = c.get("db");
    const userId = c.get("user").id;
    const now = clock.now();

    if ("connectionId" in target) {
      const row = await findUserConnection(db, userId, target.connectionId);
      if (!row) return apiError(c, 404, "not_found", connectionNotFound);
      // Disconnecting again changes nothing.
      if (row.revokedAt !== null) return c.body(null, 204);
      const snap = await snapshot(db, oauth, userId, now);
      const entry = findEntry(snap.entries, target);
      const revoked = await revokeConnections(c.env.DB, userId, [row.id], "user", now);
      // An expired connection has no grant left in KV.
      if (entry?.kind === "active") await revokeConnectionGrants(oauth, userId, revoked, null);
      return c.body(null, 204);
    }

    const snap = await snapshot(db, oauth, userId, now);
    const entry = findEntry(snap.entries, target);
    if (entry === undefined) return apiError(c, 404, "not_found", connectionNotFound);
    if (entry.kind === "active") return apiError(c, 400, "invalid_request", "この接続は connection_id で指定してください");
    // A legacy or stale grant: only KV. The subscriptions of a legacy connection cannot be told apart, so they are
    // left to expire.
    if (entry.kind === "legacy" || entry.kind === "stale") await oauth.revokeGrant(entry.grant.id, userId);
    return c.body(null, 204);
  });
